/// A byte range in the source text a node was parsed from.
///
/// Spans live on IR nodes rather than on a separate AST: the parser produces
/// IR directly, and a parallel syntax tree whose only job is to be traversed
/// would be a translation layer with no other consumer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default)]
pub struct Span {
    /// Byte offset of the first character.
    pub start: u32,
    /// Byte offset one past the last character.
    pub end: u32,
}

impl Span {
    /// A span over `start..end`.
    #[must_use]
    pub const fn new(start: u32, end: u32) -> Self {
        Self { start, end }
    }

    /// The zero-width span used for IR that no source text produced --
    /// desugared command-line goals and rules generated by the magic-set
    /// rewrite.
    #[must_use]
    pub const fn synthetic() -> Self {
        Self { start: 0, end: 0 }
    }

    /// Whether this span points at no source text.
    #[must_use]
    pub const fn is_synthetic(&self) -> bool {
        self.start == 0 && self.end == 0
    }

    /// The smallest span covering both.
    #[must_use]
    pub fn join(self, other: Self) -> Self {
        if self.is_synthetic() {
            return other;
        }
        if other.is_synthetic() {
            return self;
        }
        Self {
            start: self.start.min(other.start),
            end: self.end.max(other.end),
        }
    }
}
